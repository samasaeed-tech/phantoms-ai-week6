import numpy as np
from sentence_transformers import SentenceTransformer

model = SentenceTransformer('all-MiniLM-L6-v2')

sentences = [
    "Python is a flexible programming language used for web development and AI.",
    "Software engineers use Python to build modern scalable applications.",
    "Real Madrid won the Champions League final after a tough match.",
    "The football team secured a brilliant victory in the tournament.",
    "Freshly baked chocolate cake goes perfectly with a cup of hot coffee.",
    "Preparing a sweet cocoa dessert is my favorite way to end the day.",
    "I need to visit the bank to deposit my monthly savings.",
    "We sat by the river bank and listened to the calming water flows.",
    "Machine learning models require clean datasets for accurate training.",
    "Global economic markets are experiencing high volatility this quarter."
]

embeddings = model.encode(sentences)

def custom_cosine_similarity(v1, v2):
    dot_product = np.dot(v1, v2)
    mag_v1 = np.linalg.norm(v1)
    mag_v2 = np.linalg.norm(v2)

    if mag_v1 == 0 or mag_v2 == 0:
        return 0.0

    return dot_product / (mag_v1 * mag_v2)

def euclidean_distance(v1, v2):
    return np.linalg.norm(v1 - v2)

cos_val = custom_cosine_similarity(embeddings[0], embeddings[1])
euc_val = euclidean_distance(embeddings[0], embeddings[1])
print(f"جملة (1) مع جملة (2) -> Cosine: {cos_val:.4f} | Euclidean Distance: {euc_val:.4f}")

v1_scaled = embeddings[0] * 10
cos_scaled = custom_cosine_similarity(v1_scaled, embeddings[1])
euc_scaled = euclidean_distance(v1_scaled, embeddings[1])
print(f"\n[تجربة الحجم] بعد ضرب الجملة الأولى في 10:")
print(f"الـ Cosine Similarity الجديد: {cos_scaled:.4f}")
print(f"المسافة الإقليدية الجديدة: {euc_scaled:.4f}\n")
print("="*60)

query = "I want to build a machine learning model using Python."
query_embedding = model.encode(query)

similarities = []
for idx, emb in enumerate(embeddings):
    score = custom_cosine_similarity(query_embedding, emb)
    similarities.append((idx, score))

similarities.sort(key=lambda x: x[1], reverse=True)

print(f"السؤال البحثي: '{query}'\n")
print("أقرب 3 جمل مطابقة للمعنى:")
for rank, (idx, score) in enumerate(similarities[:3], 1):
    print(f"{rank}. [درجة التشابه: {score:.4f}] - {sentences[idx]}")