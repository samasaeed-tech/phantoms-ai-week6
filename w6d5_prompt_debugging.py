fixed_prompt_template = """
[System]
You are a precise data extraction and review analysis assistant. You must output ONLY valid JSON format with no markdown wrappers or extra text.

[Context]
Analyze the provided customer review.

[Instruction]
1. Determine if the review is Positive, Negative, or Neutral.
2. Provide a short, concise explanation for the sentiment.
3. Extract any mentioned names, locations, or products as a list of strings.
4. If any information is missing or unknown, return null or an empty list.

[Output Format (JSON)]
{
  "sentiment": "Positive/Negative/Neutral",
  "reason": "string",
  "entities": ["string"]
}

[Review to Analyze]
{review}
"""

def test_prompts(prompts_list, is_fixed=False):
    success_count = 0
    total_runs = 0

    for prompt in prompts_list:
        for _ in range(3):
            try:
                if is_fixed:
                    formatted_prompt = fixed_prompt_template.format(review=prompt)
                else:
                    formatted_prompt = prompt

                response = model.generate_content(
                    formatted_prompt,
                    generation_config=genai.GenerationConfig(temperature=0.7)
                )

                text_res = response.text.strip()
                if text_res.startswith("```json"):
                    text_res = text_res[7:-3].strip()
                elif text_res.startswith("```"):
                    text_res = text_res[3:-3].strip()

                json.loads(text_res)
                success_count += 1
            except Exception:
                pass
            total_runs += 1
            time.sleep(1)

    return success_count, total_runs

print("Testing Flawed Prompts...")
flawed_success, total = test_prompts(flawed_prompts, is_fixed=False)
print(f"Flawed JSON Success: {flawed_success}/{total}")

print("Testing Fixed Prompts...")
fixed_success, total = test_prompts(flawed_prompts, is_fixed=True)
print(f"Fixed JSON Success: {fixed_success}/{total}")