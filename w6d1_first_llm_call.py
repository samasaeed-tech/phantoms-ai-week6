import os
from google.colab import userdata
from google import genai
from google.genai import types

api_key = userdata.get('GEMINI_API_KEY')
client = genai.Client(api_key=api_key)


user_question = "اشرح لي باختصار إزاي الموديل بيتنبأ بالكلمة اللي بعدها؟"

response_1 = client.models.generate_content(
    model='gemini-3.8-flash',
    contents=user_question,
    config=types.GenerateContentConfig(
        system_instruction="أنت مدرس صبور ومبسط، وتشرح المفاهيم الصعبة بأمثلة سهلة من الواقع.",
        temperature=0.7,
    )
)
print(response_1.text)
print(f"عدد الـ Tokens المستخدمة: {response_1.usage_metadata.total_token_count}\n")

response_2 = client.models.generate_content(
    model='gemini-3.8-flash',
    contents=user_question,
    config=types.GenerateContentConfig(
        system_instruction="أنت خبير تقني مختصر جداً، أجب في سطرين كحد أقصى وبدون مقدمات.",
        temperature=0.3,
    )
)
print(response_2.text)
print(f"عدد الـ Tokens المستخدمة: {response_2.usage_metadata.total_token_count}")